def _flake(cx, cy, r, cls="n t"):
    out = ""
    for i in range(6):
        a = math.radians(i * 60 - 90)
        x2, y2 = cx + r * math.cos(a), cy + r * math.sin(a)
        out += L(f"{cx:.1f}", f"{cy:.1f}", f"{x2:.1f}", f"{y2:.1f}", cls)
        mx, my = cx + 0.6 * r * math.cos(a), cy + 0.6 * r * math.sin(a)
        for s in (-1, 1):
            b = a + s * math.radians(40)
            out += L(f"{mx:.1f}", f"{my:.1f}", f"{mx + 0.3 * r * math.cos(b):.1f}", f"{my + 0.3 * r * math.sin(b):.1f}", cls)
    return out + C(cx, cy, r * 0.16, "e")


def _waves(y, x0=14, x1=186, step=24, cls="n"):
    d = f"M{x0} {y}"
    x = x0
    while x < x1:
        d += f" q{step/4} -6 {step/2} 0 q{step/4} 6 {step/2} 0"
        x += step
    return P(d, cls)


