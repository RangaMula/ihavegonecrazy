def evo_table(rows, heads):
    th = "".join("<th>%s</th>" % h for h in heads)
    tr = "".join("<tr>%s</tr>" % "".join('<td class="%s">%s</td>' % (c, E(v)) for c, v in zip(
        ["c-bn", "c-bp", "c-ep", "c-fr"][:len(r)] if len(r) == 4 else ["c-ep"] * (len(r) - 1) + ["c-fr"], r)) for r in rows)
    return '<table class="tr" style="font-size:10.5pt;"><thead><tr>%s</tr></thead><tbody>%s</tbody></table>' % (th, tr)

